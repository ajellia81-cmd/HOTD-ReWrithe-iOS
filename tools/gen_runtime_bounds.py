"""Generates the runtime's logging overrides of the port's boundaries (src/game/runtime.h, class RuntimeBounds).

Every `virtual ... { ... }` stub in src/port/decl/*.h (the routines not ported yet) gets an override that reports the
call (`missing("name", address)`: logged once, counted for hotd --boundary-report; the address from the stub's
`// 0x...` comment, 0 if none) and then does what the stub does (returns its default). The runtime's own
implementations override these again, so a boundary the runtime does not implement shows up in the log instead of
silently doing nothing. Stubs whose body is PC Mode's own implementation (pmx_*, pm_view_test) are left out.

    py tools/gen_runtime_bounds.py <out.inc>        (CMake runs it before building hotd)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DECL = ROOT / "src" / "port" / "decl"
# not boundaries of the game: the harness hooks
SKIP = {"orig_fp", "relocate", "copro"}
PAT = re.compile(r"^\s*virtual\s+(?P<ret>[\w:<>\s\*&]+?)\s+(?P<name>\w+)\((?P<args>[^)]*)\)\s*\{(?P<body>.*)\}\s*(?://\s*(?P<addr>0x[0-9A-Fa-f]+)?.*)?$")


def main():
    out = pathlib.Path(sys.argv[1])
    lines = ["// GENERATED by tools/gen_runtime_bounds.py from src/port/decl/*.h: do not edit.",
             "// The boundaries (routines not ported yet): report the call once, then the stub's default."]
    seen = set()
    for f in sorted(DECL.glob("*.h")):
        for line in f.read_text(encoding="utf-8").splitlines():
            m = PAT.match(line)
            if not m or m["name"] in SKIP or m["name"] in seen:
                continue
            # the PC-only helper copies whose default body is PC Mode's own implementation (pmx_*, pm_view_test:
            # src/port/game.h): implemented for the runtime, so not reported
            if "pmx_" in m["body"] or "pm_view_test" in m["body"]:
                continue
            seen.add(m["name"])
            lines.append(f"    {m['ret']} {m['name']}({m['args']}) override {{ missing(\"{m['name']}\", {m['addr'] or '0'});{m['body'].strip()} }}")
    text = "\n".join(lines) + "\n"
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
