#!/usr/bin/env bash
# ios (2026-11-12, docs/ios.md): builds the iPhone / iPad app with Xcode and packages it as an unsigned .ipa for
# LiveContainer (or another sideloading tool that signs it on the phone). Runs on a Mac with Xcode, CMake 3.21+ and
# Python 3 (the GitHub workflow .github/workflows/ios.yml runs it on macos-latest).
#
#   ios/build.sh                  fetch the third-party sources (once), build, package
#   ios/build.sh --no-fetch       use what is in build-ios-deps already
#   BUILD=... DEPS=... OUT=...    other folders (defaults: build-ios, build-ios-deps, build-ios/ipa)
#
# Result: $OUT/HOTD-ReWrithe-ios-v<version>.ipa (+ .sha256). NO GAME DATA is in it: the player copies their own
# arcade ROM zip and 1998 PC game into the app's Documents folder (docs/ios.md).
set -euo pipefail
cd "$(dirname "$0")/.."
SRC="$PWD"
BUILD="${BUILD:-$SRC/build-ios}"
DEPS="${DEPS:-$SRC/build-ios-deps}"
OUT="${OUT:-$BUILD/ipa}"
FETCH=1
[[ "${1:-}" == "--no-fetch" ]] && FETCH=0

# the same pinned sources as the release workflow (.github/workflows/release.yml; licences in NOTICE.md)
SDL3_TAG="${SDL3_TAG:-release-3.2.10}"
MUSASHI_COMMIT="${MUSASHI_COMMIT:-313ebf1bd9f4d0d93341eb5ce21fd8a119e9dbdd}"
DR_LIBS_COMMIT="${DR_LIBS_COMMIT:-51e61d308dde6b437fce0c5fabb32cd86b40f4d7}"
MAME_TAG="${MAME_TAG:-mame0289}"

mkdir -p "$DEPS"
if [[ $FETCH == 1 ]]; then
    (
        cd "$DEPS"
        if [[ ! -f musashi/m68kmake.c ]]; then
            rm -rf musashi
            git clone -q https://github.com/kstenerud/Musashi musashi
            git -C musashi checkout -q "$MUSASHI_COMMIT"
            rm -rf musashi/m68kfpu.c musashi/m68kmmu.h musashi/softfloat musashi/.git
        fi
        if [[ ! -f dr_libs/dr_mp3.h ]]; then
            rm -rf dr_libs
            git clone -q https://github.com/mackron/dr_libs dr_libs
            git -C dr_libs checkout -q "$DR_LIBS_COMMIT"
        fi
        [[ -f stb/stb_vorbis.c ]] || { rm -rf stb; git clone -q --depth 1 https://github.com/nothings/stb stb; }
        mkdir -p mame_scsp
        for f in scsp.cpp scsp.h scspdsp.cpp scspdsp.h; do
            [[ -f "mame_scsp/$f" ]] || curl -fsSL -o "mame_scsp/$f" \
                "https://raw.githubusercontent.com/mamedev/mame/$MAME_TAG/src/devices/sound/$f"
        done
    )
fi

# the arcade sound's 68000 core is generated by Musashi's m68kmake, which a cross build cannot run: built for this Mac
# and run here (no optimisation: an optimised build once dropped an opcode-mask bit, CMakeLists.txt)
if [[ ! -f "$DEPS/m68kgen/m68kops.c" ]]; then
    mkdir -p "$DEPS/m68kgen"
    cc -O0 -w -o "$DEPS/m68kmake" "$DEPS/musashi/m68kmake.c"
    "$DEPS/m68kmake" "$DEPS/m68kgen" "$DEPS/musashi/m68k_in.c"
fi

cmake -S "$SRC" -B "$BUILD" -G Xcode \
    -DCMAKE_SYSTEM_NAME=iOS -DCMAKE_OSX_ARCHITECTURES=arm64 -DCMAKE_OSX_DEPLOYMENT_TARGET=15.0 \
    -DHOTD_FETCH_SDL3=ON -DHOTD_SDL3_TAG="$SDL3_TAG" -DHOTD_LOCAL_ICON=OFF \
    -DHOTD_STB_DIR="$DEPS/stb" -DHOTD_DR_LIBS_DIR="$DEPS/dr_libs" \
    -DHOTD_ARCADE_SOUND=ON -DHOTD_MUSASHI_DIR="$DEPS/musashi" -DHOTD_SCSP_DIR="$DEPS/mame_scsp" \
    -DHOTD_M68KOPS_DIR="$DEPS/m68kgen" \
    -DHOTD_EXPERIMENTAL_MODES=OFF -DHOTD_TOTD_MODE=ON -DHOTD_SURVIVAL_MODE=ON -DHOTD_HORDE_MODE=ON \
    -DPython3_EXECUTABLE="$(command -v python3)"

cmake --build "$BUILD" --config Release --target hotd -- -sdk iphoneos -quiet \
    CODE_SIGNING_ALLOWED=NO CODE_SIGNING_REQUIRED=NO CODE_SIGN_IDENTITY=""

app="$(find "$BUILD" -type d -name 'HOTDReWrithe.app' -path '*Release-iphoneos*' | head -1)"
[[ -n "$app" ]] || { echo "build/ios: HOTDReWrithe.app not found" >&2; exit 1; }
ver="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$app/Info.plist")"

# the icon: the game's own neutral icon (src/res/hotd.ico, never SEGA's) as the iPhone / iPad home screen sizes
if command -v sips > /dev/null; then
    tmp="$(mktemp -d)"
    if sips -s format png "$SRC/src/res/hotd.ico" --out "$tmp/icon.png" > /dev/null 2>&1; then
        for s in "AppIcon60x60@2x:120" "AppIcon60x60@3x:180" "AppIcon76x76@2x~ipad:152" "AppIcon83.5x83.5@2x~ipad:167"; do
            sips -z "${s##*:}" "${s##*:}" "$tmp/icon.png" --out "$app/${s%%:*}.png" > /dev/null
        done
    fi
    rm -rf "$tmp"
fi

# checks: an arm64 executable, the game's data folder in the bundle, no game data
lipo -info "$app/HOTDReWrithe" | grep -q arm64
[[ -d "$app/data/ui" && -d "$app/data/fonts" ]] || { echo "build/ios: the bundle has no data/ folder" >&2; exit 1; }
if find "$app" -iname '*.zip' -o -iname 'THOTD.EXE' -o -iname '*.rbh' | grep -q .; then
    echo "build/ios: game data found in the bundle" >&2; exit 1
fi
codesign --remove-signature "$app/HOTDReWrithe" 2> /dev/null || true

rm -rf "$OUT" && mkdir -p "$OUT/Payload"
cp -R "$app" "$OUT/Payload/"
ipa="HOTD-ReWrithe-ios-v$ver.ipa"
(cd "$OUT" && zip -qry "$ipa" Payload && shasum -a 256 "$ipa" > "$ipa.sha256" && rm -rf Payload)
echo "build/ios: $OUT/$ipa ($(du -h "$OUT/$ipa" | cut -f1))"
